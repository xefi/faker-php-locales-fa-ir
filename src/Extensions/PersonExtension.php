    /**
     * Return an Iranian national code (کد ملی, 10 digits with one check digit).
     *
     * @return string
     */
    public function codeMelli(): string
    {
        $code = sprintf('%03d%06d', $this->randomizer->getInt(1, 999), $this->randomizer->getInt(0, 999999));

        $sum = 0;
        for ($i = 0; $i < 9; $i++) {
            $sum += (int) $code[$i] * (10 - $i);
        }

        $remainder = $sum % 11;

        return $code.($remainder < 2 ? $remainder : 11 - $remainder);
    }
